DO $w$
DECLARE fw uuid; r record; cur text; n int := 0; skipped int := 0;
BEGIN
  SELECT id INTO fw FROM frameworks WHERE code = 'QNSA' AND version = 'final-2026';
  IF fw IS NULL THEN RAISE EXCEPTION 'الإصدار QNSA/final-2026 غير موجود — شغّل الترحيل 064 أولاً'; END IF;

  FOR r IN SELECT * FROM (VALUES
    ('1.2.2', 'تطبيق خطط شاملة، طويلة وقصيرة المدى، تساهم في تحقيق رؤية ورسالة وأهداف المدرسة.', 'تطبيق خطط شاملة، (طويلة وقصيرة المدى)، تساهم في تحقيق رؤية ورسالة وأهداف المدرسة.'),
    ('3.1.2', 'جودة التقييمات الداخلية والتغذية الراجعة المقدمة للطلبة.', 'جودة التقييمات الداخلية، والتغذية الراجعة المقدمة للطلبة.'),
    ('3.1.3', 'تقدم مستوى أداء الطلبة في التقييمات الداخلية «المدرسية».', 'تقدم مستوى أداء الطلبة في التقييمات الداخلية (المدرسية).'),
    ('3.1.6', 'تقدم مستوى أداء الطلبة في الاختبارات الدولية الموحدة (TIMMS – PIRLS – PISA).', 'تقدم مستوى أداء الطلبة في الاختبارات الدولية الموحدة. (TIMSS - PIRLS - PISA)'),
    ('3.1.7', 'تقدم الأطفال وتطور مهاراتهم في مرحلة الروضة، إن وجدت في المدرسة.', 'تقدم الأطفال وتطور مهاراتهم في مرحلة الروضة. (إن وجدت في المدرسة)'),
    ('3.2.6', 'توفير برامج الإرشاد الأكاديمي والمهني للطلبة، خاص بالمرحلتين الإعدادية والثانوية.', 'توفير برامج الإرشاد الأكاديمي والمهني للطلبة (خاص بالمرحلتين الإعدادية والثانوية).'),
    ('4.2.1', 'برامج وأنشطة تساهم في تعزيز القيم والهوية الوطنية والثقافة القطرية.', 'تنفيذ برامج وأنشطة تساهم في تعزيز القيم والهوية الوطنية والثقافة القطرية.'),
    ('4.2.4', 'جودة تطبيق مواد اللغة العربية والتربية الإسلامية والتاريخ القطري والمواطنة.', 'جودة تطبيق مواد اللغة العربية، والتربية الإسلامية، والتاريخ القطري والمواطنة.'),
    ('5.2.4', 'معامل الحاسب مجهزة بالأجهزة والبرمجيات التعليمية التي تدعم تعلم الطلبة في مجالات تكنولوجيا المعلومات والعلوم.', 'معامل الحاسب مجهزة بالأجهزة والبرمجيات التعليمية التي تدعم تعلم الطلبة في مجالات تكنولوجيا المعلومات والعلوم التقنية.'),
    ('5.2.5', 'القاعات والملاعب الرياضية مجهزة وتلبي احتياجات الأنشطة الرياضية.', 'القاعات والملاعب الرياضية مجهزة وتلبي احتياجات الأنشطة الرياضية المتنوعة.'),
    ('5.2.7', 'توفير مرافق مدرسية تخصصية تتماشى مع متطلبات منهج المدرسة وتدعم تحقيق أهدافه التعليمية والتربوية.', 'توفير مرافق مدرسية تخصّصية تتوافق مع متطلبات منهج المدرسة وتدعم تحقيق أهدافه التعليمية والتربوية.'),
    ('5.2.8', 'توفير مرافق مدرسية تخصصية مجهزة تلبي احتياجات الطلبة ذوي الإعاقة وتدعم تعلمهم، إن وجد.', 'توفير مرافق مدرسية تخصّصية مجهزة تلبي احتياجات الطلبة ذوي الإعاقة وتدعم تعلمهم. (إن وجد)')
  ) AS v(code, old_name, new_name) LOOP
    SELECT name_ar INTO cur FROM framework_nodes
     WHERE framework_id = fw AND level = 3 AND code = r.code;
    IF NOT FOUND THEN RAISE EXCEPTION 'المعيار الفرعي % غير موجود', r.code; END IF;

    IF cur = r.new_name THEN skipped := skipped + 1; CONTINUE; END IF;
    IF cur <> r.old_name THEN
      RAISE EXCEPTION 'نصّ المعيار % في القاعدة غير متوقَّع: «%»', r.code, cur;
    END IF;

    UPDATE framework_nodes SET name_ar = r.new_name
     WHERE framework_id = fw AND level = 3 AND code = r.code;
    n := n + 1;
  END LOOP;

  RAISE NOTICE 'حُدِّث % معياراً فرعياً · سبق تحديثه %', n, skipped;
