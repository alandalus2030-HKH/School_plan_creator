-- 056 — تقييد قراءة جدول schools على مدرسة المستخدم فقط
-- ════════════════════════════════════════════════════════════════
-- المشكلة (إفصاح معلومات عبر المستأجرين):
--   سياسة 026 "schools_read" كانت USING (auth.uid() IS NOT NULL) — أي أن
--   أي مستخدم مسجّل (بما فيهم مدير مدرسة واحدة) يستطيع قراءة أسماء كل مدارس
--   المنصّة. ظهر ذلك في قائمة «الجهة/المؤسسة» بنموذج إنشاء المستخدم التي كانت
--   تسرد كل المدارس. مدير مدرسة يجب ألّا يعرف بوجود المدارس الأخرى.
--
-- الإصلاح:
--   القراءة من العميل تقتصر على مدرسة المستخدم الفعّالة عبر my_school_id()
--   (التي تُرجع active_school_id لمشرف النظام المتقمّص — ترحيل 015/016).
--
-- لا ينكسر شيء:
--   • قراءات العميل الوحيدة لـ schools هي «مدرستي» أو «المدرسة المتقمَّصة»
--     (PermissionsContext، عمود المدرسة في صفحة المستخدمين، طباعة الدليل) —
--     كلها id = my_school_id().
--   • كل عمليات مشرف النظام/مالك المجموعة على المدارس (schools/list,
--     schools/overview, impersonate, groups/*) تمرّ عبر APIs خادمية
--     (service role) تتجاوز RLS — فلا تتأثر.
--   • كل عمليات الكتابة على schools خادمية (service role) — بلا سياسة كتابة عميل.
-- ════════════════════════════════════════════════════════════════

DROP POLICY IF EXISTS "schools_read" ON schools;

CREATE POLICY "schools_read" ON schools FOR SELECT
USING (id = my_school_id());

