CREATE TABLE IF NOT EXISTS qnsa_standards (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code        TEXT NOT NULL,                 -- '1' / '1.1' / '1.1.1'
  level       SMALLINT NOT NULL CHECK (level IN (1, 2, 3)),
  parent_code TEXT,                          -- NULL للمستوى الأول
  name_ar     TEXT NOT NULL,
  is_system   BOOLEAN NOT NULL DEFAULT true, -- رسمي (مقفل الاسم) / مخصص
  school_id   UUID,                          -- NULL = رسمي عام؛ قيمة = مخصص لمدرسة
  is_active   BOOLEAN NOT NULL DEFAULT true,
  sort_order  INT NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ DEFAULT now()
);

-- فهرس فريد للبنود الرسمية (school_id IS NULL) + فريد مركب للمخصصة
CREATE UNIQUE INDEX IF NOT EXISTS qnsa_standards_official_code
  ON qnsa_standards (code) WHERE school_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS qnsa_standards_school_code
  ON qnsa_standards (school_id, code) WHERE school_id IS NOT NULL;

-- ════ RLS ════
ALTER TABLE qnsa_standards ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "qnsa_read" ON qnsa_standards;
CREATE POLICY "qnsa_read" ON qnsa_standards FOR SELECT
USING (auth.uid() IS NOT NULL AND (school_id IS NULL OR school_id = my_school_id()));

-- البنود المخصصة فقط قابلة للكتابة من العميل (manage_plans أو manage_settings)
-- البنود الرسمية لا تُعدَّل إلا بترحيل (service role)
DROP POLICY IF EXISTS "qnsa_custom_insert" ON qnsa_standards;
CREATE POLICY "qnsa_custom_insert" ON qnsa_standards FOR INSERT
WITH CHECK (
  school_id = my_school_id() AND is_system = false
  AND (my_perm('manage_plans') OR my_perm('manage_settings'))
);

DROP POLICY IF EXISTS "qnsa_custom_update" ON qnsa_standards;
CREATE POLICY "qnsa_custom_update" ON qnsa_standards FOR UPDATE
USING (
  school_id = my_school_id() AND is_system = false
  AND (my_perm('manage_plans') OR my_perm('manage_settings'))
)
WITH CHECK (
  school_id = my_school_id() AND is_system = false
  AND (my_perm('manage_plans') OR my_perm('manage_settings'))
);

DROP POLICY IF EXISTS "qnsa_custom_delete" ON qnsa_standards;
CREATE POLICY "qnsa_custom_delete" ON qnsa_standards FOR DELETE
USING (
  school_id = my_school_id() AND is_system = false
  AND (my_perm('manage_plans') OR my_perm('manage_settings'))
);

