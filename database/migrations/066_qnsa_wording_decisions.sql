SELECT v.code AS المعيار,
       CASE WHEN fn.name_ar = v.expected THEN 'مطابق' ELSE 'مختلف' END AS الحالة
FROM (VALUES
  ('1.2.2', 'تطبيق خطط شاملة، (طويلة وقصيرة المدى)، تساهم في تحقيق رؤية ورسالة وأهداف المدرسة.'),
  ('3.1.2', 'جودة التقييمات الداخلية، والتغذية الراجعة المقدمة للطلبة.'),
  ('3.1.3', 'تقدم مستوى أداء الطلبة في التقييمات الداخلية (المدرسية).'),
  ('3.1.6', 'تقدم مستوى أداء الطلبة في الاختبارات الدولية الموحدة. (TIMSS - PIRLS - PISA)'),
  ('3.1.7', 'تقدم الأطفال وتطور مهاراتهم في مرحلة الروضة. (إن وجدت في المدرسة)'),
