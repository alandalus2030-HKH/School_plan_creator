) AS v(code, expected)
JOIN frameworks f ON f.code = 'QNSA' AND f.version = 'final-2026'
LEFT JOIN framework_nodes fn ON fn.framework_id = f.id AND fn.level = 3 AND fn.code = v.code
ORDER BY string_to_array(v.code, '.')::int[];
