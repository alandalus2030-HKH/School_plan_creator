  ('5.2.5', 'القاعات والملاعب الرياضية مجهزة وتلبي احتياجات الأنشطة الرياضية المتنوعة.'),
  ('5.2.7', 'توفير مرافق مدرسية تخصّصية تتوافق مع متطلبات منهج المدرسة وتدعم تحقيق أهدافه التعليمية والتربوية.'),
