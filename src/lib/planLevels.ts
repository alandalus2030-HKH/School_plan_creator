/**
 * أيّ مستوى من الإطار يقابل مستوى الخطة رقم `levelNum`؟
 *
 * لا يصحّ افتراض أن مستوى الخطة N = مستوى الإطار N: خطةٌ استراتيجية
 * مستواها الثاني «هدف استراتيجي» لا «جانب»، ولو افترضنا التطابق لفتح
 * المنتقي لها قائمة جوانب الاعتماد.
 *
 * المطابقة بالاسم المخزَّن في الخطة (`plans.level_names`)، فتعمل مع
 * أيّ تسمية تختارها المدرسة: اسمٌ غير معروف ⇒ مستوىً حرّ (null).
 */
export function frameworkLevelOf(levelNames: unknown, levelNum: number): number | null {
  const names = Array.isArray(levelNames) ? levelNames : []
  const name = String(names[levelNum - 1] ?? '').trim()
  if (!name) return null
  const hit = Object.entries(FRAMEWORK_LEVEL_LABELS).find(([, label]) => label === name)
  return hit ? Number(hit[0]) : null
}

/**
 * مستوى الإطار المقابل لمستوى الخطة — **من القالب أوّلاً**.
 *
 * `plans.framework_levels` منسوخٌ من القالب عند الميلاد، وهو تقابلٌ
 * **مُعلَن**: صفرٌ (أو غيابه) = مستوىً حرّ. وما سبق 096 لا مصفوفة له،
 * فيُقرأ بمطابقة الاسم كما كان — ولا يتبدّل تحت صاحبه.
 *
 * والمطابقة بالاسم وحدها كانت فخّاً: مدرسةٌ تسمّي مستواها «مجالات
 * التحسين» — وهو اسم الوثيقة نفسها لقالب التحسين — **يُطفأ عندها
 * منتقي الإطار صامتاً**، فلا تدري لمَ لا تُعرض بنود الاعتماد.
 */
export function frameworkLevelFor(
  plan: { level_names?: unknown; framework_levels?: unknown } | null | undefined,
  levelNum: number,
): number | null {
  const fw = Array.isArray(plan?.framework_levels) ? plan!.framework_levels as any[] : []
  if (fw.length) {
    const v = Number(fw[levelNum - 1] ?? 0)
    return v >= 1 && v <= 4 ? v : null
  }
  return frameworkLevelOf(plan?.level_names, levelNum)
}

