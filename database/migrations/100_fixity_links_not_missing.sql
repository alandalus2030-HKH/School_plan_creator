-- ════════════════════════════════════════════════════════════════
-- 100 · الفيديو ليس ملفّاً مفقوداً — مسحُ وسمٍ كاذب
--
-- ── كيف وُجد ──
-- من بيانات الاختبار نفسها: استعلامُ البصمات على المهمّة المستقلّة
-- أخرج ستّة مرفقات، خمسةٌ منها مبصومةٌ بـ64 خانة، والسادس
-- `Shark Tank| …` — **فيديو يوتيوب** موسومٌ `missing`.
--
-- ── والآليّة مكشوفة ──
-- صفُّ الفيديو يحمل في `file_url` صورةَ الغلاف
-- (`https://img.youtube.com/vi/<id>/maxresdefault.jpg`) لا مساراً في
-- التخزين. فالفحص الدوريّ يناولها `parseStorageUrl` فتعود `null`،
-- فيُحسب الصفُّ «مفقوداً» ويُكتب الوسم. و`schoolFiles` لم تكن تقرأ
-- `video_url` أصلاً، فلا سبيل لها أن تعرف أنه رابط.
--
-- ── ولمَ لم يكن عطباً هيّناً ──
-- شريط «سلامة الأرشيف» يحمرّ ويقول «مفقود ١» **ولا يبيضُّ أبداً**،
-- والصفُّ يُعدّ في «بلا بصمة» فيُنقص نسبةَ المبصوم بلا ذنب، وكلُّ فحصٍ
-- يُعيد الوسم فالعدد ينمو مع كلّ فيديو. والوثيقة §11 تقول إن قيمة
-- البصمة «أن يُكتشف التلف **قبل** أن تُطلب الأدلة، لا يوم الزيارة» —
-- وإنذارٌ أحمرُ دائمٌ كاذب يقتل الإنذار الصادق حين يأتي.
--
-- ── والعلاج شطران ──
-- · المنفذ: `fixity/route.ts` يستبعد ما له `video_url` من الختم
--   والفحص والعدّ (مدفوعٌ مع هذا الترحيل).
-- · وهذا الملفّ: يمسح ما وُسم كاذباً قبل الإصلاح.
--
-- 🔁 **تصحيحُ وسمٍ لا حذفُ بيانات**: لا صفَّ يُمسّ، ولا رابطَ يُحذف،
--    ولا بصمةَ تُستبدَل. والمعكوسُ بترحيلٍ واحد إن لزم.
-- ════════════════════════════════════════════════════════════════

BEGIN;

-- الشرطُ الحاكم `video_url IS NOT NULL` — هو عينُه الذي يستبعد به
-- المنفذُ الآن، فلا يفترقان: «الفحص يكون على الشرط الحاكم لا على نصٍّ
-- عابر». ولا يُلمَس `last_fixity_at`: أن المسحة جرت **واقعةٌ صادقة**،
-- وإنما الحكمُ الذي كتبته كان خطأً.
UPDATE evidence_files
   SET fixity_status = NULL
 WHERE video_url IS NOT NULL
   AND fixity_status = 'missing';

COMMENT ON COLUMN evidence_files.fixity_status IS
  'حال الفحص الدوريّ: ok · mismatch · missing — و**الفيديو خارجَه** فيبقى NULL: رابطٌ لا بايتات (100)';

COMMIT;

